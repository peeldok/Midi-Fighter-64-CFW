static uint8_t boot_animation_map_key(uint8_t key)
{
    if (key >= 64) return key;

    uint8_t row = (uint8_t)((key >> 2) & 0x07);
    uint8_t col = (uint8_t)((key & 0x03) + (key >= 32 ? 4 : 0));

    uint8_t mapped_row = col;
    uint8_t mapped_col = (uint8_t)(7 - row);

    return (uint8_t)((mapped_row << 2) + (mapped_col & 0x03) + (mapped_col >= 4 ? 32 : 0));
}

static void boot_animation_set_palette(uint8_t key, uint8_t velocity)
{
    if (key >= 64) return;
    fastrgb_palette_single(boot_animation_map_key(key), 0, velocity);
}

static void boot_animation_discard_midi(void)
{
    if (USB_DeviceState != DEVICE_STATE_Configured) return;

    MIDI_EventPacket_t input_event;
    uint8_t count = 0;

    while (count < 64 && MIDI_Device_ReceiveEventPacket(&input_event)) {
        count++;
    }
}

static void boot_animation_usb_tick(void)
{
    boot_animation_discard_midi();
    wdt_reset();
}

static void boot_animation_wait_ms(uint16_t ms)
{
    while (ms--) {
        boot_animation_usb_tick();
        _delay_ms(1);
    }
}

static void boot_animation_show(void)
{
    default_display_run();
    led_update_pixels(g_display_buffer);
}

void boot_animation_play(void)
{
    uint16_t pos = 0;
    const uint16_t size = sizeof(boot_animation_data);

    fastrgb_clear();
    boot_animation_show();

    while (pos + 3U <= size) {
        uint16_t delay_ms = (uint16_t)pgm_read_byte(&boot_animation_data[pos]);
        delay_ms |= (uint16_t)pgm_read_byte(&boot_animation_data[pos + 1U]) << 8;
        uint8_t count = pgm_read_byte(&boot_animation_data[pos + 2U]);
        pos += 3U;

        boot_animation_wait_ms(delay_ms);

        for (uint8_t i = 0; i < count; i++) {
            if (pos + 2U > size) break;
            uint8_t key = pgm_read_byte(&boot_animation_data[pos++]);
            uint8_t velocity = pgm_read_byte(&boot_animation_data[pos++]);
            boot_animation_set_palette(key, velocity);
        }

        boot_animation_show();
        boot_animation_usb_tick();
    }

    fastrgb_clear();
    boot_animation_show();
    boot_animation_usb_tick();
}
