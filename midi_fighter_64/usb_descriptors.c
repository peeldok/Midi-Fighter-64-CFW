const uint8_t *usb_descriptor_get(uint8_t type, uint8_t index, uint16_t *size)
{
    const uint8_t *address = 0;
    uint16_t length = 0;

    if (type == 0x01 && index == 0) {
        address = device_descriptor;
        length = sizeof(device_descriptor);
    } else if (type == 0x02 && index == 0) {
        address = configuration_descriptor;
        length = sizeof(configuration_descriptor);
    } else if (type == 0x03) {
        if (index == 0) {
            address = language_string;
            length = sizeof(language_string);
        } else if (index == 1) {
            address = manufacturer_string;
            length = sizeof(manufacturer_string);
        } else if (index == 2) {
            address = product_string;
            length = sizeof(product_string);
        }
    }

    if (size) *size = length;
    return address;
}
